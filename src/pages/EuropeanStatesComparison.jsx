function CountryCards({ fields, showImage = false }) {
  return (
    <div className={`states-comparison-table${showImage ? ' states-comparison-table--images' : ''}`}>
      <div className="states-comparison-table-head">
        <span>{showImage ? 'Зображення' : 'Показник'}</span>
        {countries.map((country) => (
          <h3 key={country}>{country}</h3>
        ))}
      </div>
      {showImage
        ? countries.map((country) => (
            <figure className="states-comparison-image" key={country}>
              <div role="img" aria-label={countryData[country].imageAlt}>
                <img src={country === 'Чехія' ? praga : lisboa} alt={countryData[country].imageAlt} />
              </div>
              <figcaption>{countryData[country].imageCaption}</figcaption>
            </figure>
          ))
        : fields.map((field) => (
            <dl className="states-comparison-row" key={field}>
              <dt>{field}</dt>
              {countries.map((country) => (
                <dd key={country} data-country={country}>
                  {countryData[country][field]}
                </dd>
              ))}
            </dl>
          ))}
    </div>
  );
}

